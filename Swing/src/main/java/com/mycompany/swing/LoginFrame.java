    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
    String username = txtUsername.getText().trim();
    String password = txtPassword.getText().trim();

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter both Username and Password.");
        return;
    }

    try (java.sql.Connection conn = DBconnection.getConnection()) {
        String sql = "SELECT user_id, full_name, role FROM users WHERE username = ? AND password = ?";
        java.sql.PreparedStatement pstmt = conn.prepareStatement(sql);
        pstmt.setString(1, username);
        pstmt.setString(2, password);

        java.sql.ResultSet rs = pstmt.executeQuery();
        if (rs.next()) {
            String fullName = rs.getString("full_name");
            String role = rs.getString("role");

            javax.swing.JOptionPane.showMessageDialog(this, "Welcome, " + fullName + " (" + role + ")!");

    // Open MainDashboard and pass credentials
    new MainDashboard(fullName, role).setVisible(true);

    // Close the login window
    this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid credentials!", "Login Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnLoginActionPerformed

